import { writeFile, mkdir } from 'node:fs/promises';
import { lessons, modules, subjects, levels, sources } from '../site/assets/js/curriculum.js';
const docs = new URL('../docs/', import.meta.url);
await mkdir(docs, { recursive: true });
const core = lessons.filter((l) => l.level === 'core').length,
  advanced = lessons.filter((l) => l.level === 'advanced').length,
  extension = lessons.filter((l) => l.level === 'extension').length;
const out = [
  `# Полная карта тем · Тетрадь 7`,
  ``,
  `${lessons.length} тем / ${modules.length} модулей / ${lessons.length * 48} параметрических варианта заданий. База: ${core}, углублённые темы и сложная практика: ${advanced}, дополнительные: ${extension}.`,
  ``,
  `## Как читать карту`,
  ``,
  `**Б — базовое ядро** ФРП 7 класса (в том числе повторение необходимого материала 5–6 классов). **У — добавление углублённого курса / сложная практика**, который также включает всю базу. **+ — авторское расширение / опережение**, а не обязательная тема базового 7 класса. В одном уроке могут встречаться предваряющие или обобщающие сведения.`,
  ``,
  `Это авторская тематическая навигация по федеральным рабочим программам 2025 года, не официальная рабочая программа и не сетка учебных часов. Базовая сетка: алгебра 102 ч, геометрия 68 ч, отдельный курс вероятности и статистики 34 ч. Для углублённой алгебры ориентир — 136 ч.`,
  ``,
  `**Сопоставление УМК — тематическое, не по номерам упражнений.** Для Макарычева, Петерсон, Атанасяна и Гордина указаны ориентиры подбора. Пособие Галицкого 8–9 классов используется выборочно, только для повторения/углубления уже освоенного материала. Конкретное издание Кутузова не установлено: соответствие не выдумано. Подробнее — [УМК и источники](BOOKS.md).`,
  ``,
  `Общая схема каждого урока: памятка → КР 8 задач → ДЗ 8 других задач → разбор → при желании отчёт учителю. В практике — 12 задач. Варианты параметрические: 16 наборов чисел × 3 формы упражнения; это не 48 разных методических сюжетов.`,
  ``,
  `## Сводка модулей`,
  ``,
  `| Предмет | Модуль | Б | У | + | Всего |`,
  `|---|---|---:|---:|---:|---:|`,
];
for (const m of modules) {
  const a = lessons.filter((l) => l.module === m.id);
  out.push(
    `| ${subjects[m.subject].short} | ${m.number}. ${m.title} | ${a.filter((l) => l.level === 'core').length} | ${a.filter((l) => l.level === 'advanced').length} | ${a.filter((l) => l.level === 'extension').length} | ${a.length} |`
  );
}
for (const m of modules) {
  out.push('', `## ${subjects[m.subject].title} · ${m.number}. ${m.title}`, '', m.description, '');
  for (const l of lessons.filter((l) => l.module === m.id)) {
    const mark = l.level === 'core' ? 'Б' : l.level === 'advanced' ? 'У' : '+';
    out.push(
      `### ${l.id.toUpperCase()} · ${l.title} [${mark}]`,
      '',
      l.description,
      '',
      `**Ключевая связь:** ${l.theory.formula}`,
      '',
      ...l.theory.rules.map((s) => '- ' + s),
      '',
      `**Пример:** ${l.theory.example}`,
      '',
      `**Типичная ошибка / оговорка:** ${l.theory.pitfall}`,
      '',
      `**Ориентиры УМК:** ${l.umk.join('; ')}. **Банк:** 48 вариантов.`,
      ''
    );
  }
}
out.push(
  '## Сквозные линии и границы автоматической проверки',
  '',
  '- Алгебра: свойства действий, прикидка, подстановка и проверка, моделирование, контрпример и доказательство тождеств.',
  '- Геометрия: определения, аксиомы, теоремы-свойства и признаки, обратные утверждения, равенство треугольников, построения с анализом числа решений. Историко-аксиоматические сведения встроены в памятки, а не выделены в отдельный набор вычислений.',
  '- Вероятность и статистика: смысл шкалы, интерпретация реальных данных, изменчивость и устойчивость, свойства графов, логические утверждения. Группировки и гистограммы выделены в углублённый урок S11.',
  '- Полное доказательство и реальный чертёж проверяет учитель. Автоматически проверяются вычисления, короткие термины, выбор утверждения и допустимый порядок готовых шагов. Можно сохранить текст обоснования до 1200 символов.',
  '- Нет заявлений о сертификации по ФГОС или точном совпадении с любой редакцией учебника. Учитель сверяет план с действующей ФОП и локальной программой школы.',
  '',
  '## Использованные источники',
  '',
  ...sources.map((s) => `- [${s.title}](${s.url}). ${s.detail}`),
  '',
  'Машиночитаемые версии: [CSV](curriculum.csv), [JSON](curriculum.json). Источник данных: `site/assets/js/curriculum.js`. Перегенерация: `node scripts/export-curriculum.mjs`.',
  ''
);
await writeFile(new URL('PROGRAM.md', docs), out.join('\n'));
const cell = (s) => '"' + String(s ?? '').replace(/"/g, '""') + '"';
const rows = [
  [
    'ID',
    'Предмет',
    'Модуль',
    'Тема',
    'Уровень',
    'Содержание',
    'Ориентиры УМК',
    'Формула',
    'Вариантов',
  ],
  ...lessons.map((l) => [
    l.id,
    subjects[l.subject].title,
    modules.find((m) => m.id === l.module).title,
    l.title,
    levels[l.level].title,
    l.description + ' ' + l.theory.rules.join(' '),
    l.umk.join('; '),
    l.theory.formula,
    48,
  ]),
];
await writeFile(
  new URL('curriculum.csv', docs),
  '\uFEFF' + rows.map((r) => r.map(cell).join(';')).join('\n') + '\n'
);
await writeFile(
  new URL('curriculum.json', docs),
  JSON.stringify(
    {
      schemaVersion: 1,
      description: 'Авторская тематическая карта; сопоставление УМК ориентировочное',
      levels,
      subjects,
      modules,
      lessons,
      sources,
    },
    null,
    2
  )
);
console.log(`Экспорт программы: ${lessons.length} тем; Б ${core}, У ${advanced}, + ${extension}.`);
