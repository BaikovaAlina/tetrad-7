#!/usr/bin/env python3
"""Копирование статики и безопасная по синтаксису подстановка в КОПИЮ config.js.
ВАЖНО: JSON-экранирование и GitHub Secrets не скрывают токен в опубликованной статике.
Режим direct требует двух явных Variables. Значения секретов никогда не печатаются.
Стандартная библиотека Python; ключи не передаются в аргументах процесса.
"""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import sys
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'site'
PLACEHOLDERS = {
    'botToken': '__TELEGRAM_BOT_TOKEN__',
    'chatId': '__TELEGRAM_CHAT_ID__',
    'proxyUrl': '__TELEGRAM_PROXY_URL__',
    'turnstileSiteKey': '__TURNSTILE_SITE_KEY__',
}

def configured_values(env):
    mode = env.get('TELEGRAM_MODE', 'off').strip().lower() or 'off'
    if mode not in ('off', 'direct', 'proxy'):
        raise ValueError('TELEGRAM_MODE должен быть off, direct или proxy.')
    values = dict(PLACEHOLDERS, mode=mode, allowUnsafeDirect=False)
    if mode == 'direct':
        if env.get('ALLOW_UNSAFE_DIRECT', '').lower() != 'true':
            raise ValueError('Direct раскрывает токен. Для осознанного включения задайте ALLOW_UNSAFE_DIRECT=true.')
        token = env.get('TELEGRAM_BOT_TOKEN', '').strip()
        chat = env.get('TELEGRAM_CHAT_ID', '').strip()
        if not re.fullmatch(r'\d{5,20}:[A-Za-z0-9_-]{20,150}', token):
            raise ValueError('TELEGRAM_BOT_TOKEN отсутствует или имеет неверный формат; проверьте GitHub Secret.')
        if not re.fullmatch(r'-?\d{5,20}', chat):
            raise ValueError('TELEGRAM_CHAT_ID отсутствует или имеет неверный формат; проверьте GitHub Secret.')
        values.update(botToken=token, chatId=chat, allowUnsafeDirect=True)
    elif mode == 'proxy':
        proxy = env.get('TELEGRAM_PROXY_URL', '').strip()
        url = urlparse(proxy)
        if url.scheme != 'https' or not url.hostname or url.username or url.password or url.fragment:
            raise ValueError('TELEGRAM_PROXY_URL должен быть корректным HTTPS-адресом без логина и фрагмента.')
        key = env.get('TURNSTILE_SITE_KEY', '').strip()
        if key and not re.fullmatch(r'0x[A-Za-z0-9_-]{10,100}', key):
            raise ValueError('TURNSTILE_SITE_KEY имеет неверный формат.')
        values.update(proxyUrl=proxy, turnstileSiteKey=key or PLACEHOLDERS['turnstileSiteKey'])
    return values

def replace_property(content, name, value):
    # Заменяем целый строковый/булев литерал. Не sed и не shell-интерполяция.
    pattern = rf'(\b{re.escape(name)}\s*:\s*)(?:\'(?:[^\'\\]|\\.)*\'|"(?:[^"\\]|\\.)*"|false|true)'
    replacement = json.dumps(value, ensure_ascii=False)
    content, count = re.subn(pattern, lambda match: match.group(1) + replacement, content)
    if count != 1:
        raise ValueError(f'Ожидалось одно свойство {name} в шаблоне config.js.')
    return content

def build(output, env):
    output = Path(output).resolve()
    # Не удаляем произвольные существующие каталоги. Повторная сборка — только в наш артефакт.
    if output == ROOT or SOURCE == output or SOURCE in output.parents or output in SOURCE.parents:
        raise ValueError('Выходной каталог не должен совпадать с исходниками или содержать их.')
    if output.exists() and not (output / '.tetrad-build').exists():
        raise ValueError('Каталог уже существует и не является артефактом Тетради 7. Выберите новый каталог.')
    values = configured_values(env)
    content = (SOURCE / 'config.js').read_text(encoding='utf-8')
    for name in ('botToken', 'chatId'):
        if PLACEHOLDERS[name] not in content:
            raise ValueError('Исходный config.js должен содержать плейсхолдеры, а не реальные реквизиты.')
    for name, value in values.items():
        content = replace_property(content, name, value)
    if output.exists():
        shutil.rmtree(output)
    shutil.copytree(SOURCE, output, ignore=shutil.ignore_patterns('.DS_Store', '*.map'))
    (output / 'config.js').write_text(content, encoding='utf-8')
    (output / '.nojekyll').touch()
    (output / '.tetrad-build').write_text('Generated by scripts/build.py. Do not commit.\n')
    print(f'Статический сайт собран. Режим Telegram: {values["mode"]}.')
    if values['mode'] == 'direct':
        print('ПРЕДУПРЕЖДЕНИЕ: опубликованный config.js раскрывает токен всем посетителям.', file=sys.stderr)
    return output

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', default=str(ROOT / '_public'))
    args = parser.parse_args()
    try:
        build(args.output, os.environ)
    except (ValueError, OSError) as exc:
        print(f'Сборка остановлена: {exc}', file=sys.stderr)
        sys.exit(1)
