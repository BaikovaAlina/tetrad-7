function sumPrimeFactors(number) {
  let sum = 0;
  for (let d = 2; d * d <= number; d++)
    while (number % d === 0) {
      sum += d;
      number /= d;
    }
  return sum + (number > 1 ? number : 0);
}

function primeDivisors(number) {
  const out = [];
  for (let d = 2; d * d <= number; d++)
    if (number % d === 0) {
      out.push(d);
      while (number % d === 0) number /= d;
    }
  if (number > 1) out.push(number);
  return out;
}
