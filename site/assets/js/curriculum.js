const lessonsList = [];
function L(id, module, title, description, level, formula, rules, example, pitfall, tags = []) {
  const subject = modules.find((m) => m.id === module).subject;
  const umk =
    subject === 'algebra'
      ? level === 'core'
        ? ['Макарычев', 'Петерсон']
        : ['Петерсон', 'Галицкий: выборочно']
      : subject === 'geometry'
        ? ['Атанасян', 'Гордин: выборочно']
        : ['Отдельный курс ФРП', 'Петерсон: межкурсовые связи'];
  lessonsList.push({
    id,
    module,
    subject,
    title,
    description,
    level,
    umk,
    tags,
    theory: { formula, rules, example, pitfall },
  });
}
